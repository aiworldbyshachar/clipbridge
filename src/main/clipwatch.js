'use strict';
// Polls the system clipboard (Electron has no change event) and reports new
// text or images. Content written by the app itself is remembered so it is not
// reported back as a fresh copy.
//
// Uses Electron's synchronous clipboard API (readText/readImage/...), which
// Electron 44 replaced with an async web-style one; package.json pins 43.x.
const crypto = require('crypto');

const MAX_TEXT_BYTES = 8 * 1024 * 1024;
const MAX_HTML_CHARS = 2 * 1024 * 1024;
const MAX_IMAGE_BYTES = 30 * 1024 * 1024;

// Markers password managers put on the clipboard to ask clipboard tools to skip it.
const CONCEALED_FORMATS =
  process.platform === 'darwin'
    ? ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType']
    : ['ExcludeClipboardContentFromMonitorProcessing', 'Clipboard Viewer Ignore'];

function hashImage(img) {
  return crypto.createHash('sha1').update(img.toBitmap()).digest('hex');
}

function fixLineEndings(text) {
  return process.platform === 'win32' ? text.replace(/\r?\n/g, '\r\n') : text.replace(/\r\n/g, '\n');
}

class ClipboardWatcher {
  constructor({ clipboard, nativeImage, onClip, onError, interval = 500 }) {
    this.clipboard = clipboard;
    this.nativeImage = nativeImage;
    this.onClip = onClip;
    this.onError = onError;
    this.interval = interval;
    this.lastKind = null;
    this.lastText = null;
    this.lastImage = null;
    this.tick = 0;
  }

  start() {
    // Remember what is already on the clipboard without recording it.
    this._safePoll(true);
    this.timer = setInterval(() => this._safePoll(false), this.interval);
  }

  _safePoll(prime) {
    try {
      this._poll(prime);
    } catch (err) {
      if (!this.reportedError) {
        this.reportedError = true;
        if (this.onError) this.onError(err);
      }
    }
  }

  stop() {
    clearInterval(this.timer);
  }

  write(ev, imagePath) {
    if (ev.ctype === 'text') {
      const text = fixLineEndings(ev.text);
      if (ev.html) this.clipboard.write({ text, html: ev.html });
      else this.clipboard.writeText(text);
      this._remember('text', this.clipboard.readText(), null);
      return true;
    }
    const img = imagePath ? this.nativeImage.createFromPath(imagePath) : null;
    if (!img || img.isEmpty()) return false;
    this.clipboard.writeImage(img);
    this._remember('image', null, hashImage(this.clipboard.readImage()));
    return true;
  }

  _remember(kind, text, image) {
    this.lastKind = kind;
    this.lastText = text;
    this.lastImage = image;
  }

  _concealed() {
    try {
      const formats = this.clipboard.availableFormats();
      for (const f of CONCEALED_FORMATS) {
        if (formats.includes(f)) return true;
        if (this.clipboard.has && this.clipboard.has(f)) return true;
        if (this.clipboard.readBuffer(f).length > 0) return true;
      }
    } catch {}
    return false;
  }

  _poll(prime) {
    let text = '';
    try {
      text = this.clipboard.readText();
    } catch {
      return;
    }
    if (typeof text !== 'string') throw new Error('clipboard.readText() did not return a string');

    if (text.trim()) {
      if (this.lastKind === 'text' && text === this.lastText) return;
      this._remember('text', text, null);
      if (prime || this._concealed() || Buffer.byteLength(text, 'utf8') > MAX_TEXT_BYTES) return;
      let html = '';
      try {
        html = this.clipboard.readHTML() || '';
      } catch {}
      if (html.length > MAX_HTML_CHARS) html = '';
      this.onClip({ ctype: 'text', text, html });
      return;
    }

    // Decoding an image is heavier than reading text, so images are checked
    // on every other tick.
    if (!prime && this.tick++ % 2) return;
    let img;
    try {
      img = this.clipboard.readImage();
    } catch {
      return;
    }
    // An empty read also happens for a moment while another app holds the
    // clipboard, so it must not reset what was seen last (or the same content
    // would be reported again right after).
    if (!img || img.isEmpty()) return;
    const hash = hashImage(img);
    if (this.lastKind === 'image' && hash === this.lastImage) return;
    this._remember('image', null, hash);
    if (prime || this._concealed()) return;
    const png = img.toPNG();
    if (png.length > MAX_IMAGE_BYTES) return;
    const { width, height } = img.getSize();
    this.onClip({ ctype: 'image', png, w: width, h: height });
  }
}

module.exports = { ClipboardWatcher };
